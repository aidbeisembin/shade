// «Слышу речь»: голос уже есть, а текста по нему ещё нет.
//
// Ядро режет живую запись на куски по паузам от 500 мс (VAD, детектор речи) и
// присылает текст куска целиком после паузы. Если говорить без пауз, лента молчит
// 10-15 с и дольше (по логу: медиана куска 4,6 с, 10 % кусков длиннее 14 с), хотя
// запись идёт. Чтобы это было видно, лента смотрит на уровень голоса (событие
// recording-level, lib/recording-level.ts) и показывает «Слышу речь», пока по
// последнему голосу не пришёл текст.
//
// Ожидание: голос был позже последней реплики и не дольше HOLD_MS назад. HOLD_MS
// перекрывает паузу VAD и распознавание куска (меньше секунды), чтобы строка не
// мигала между словами. Если по голосу текст так и не пришёл (шум, кашель,
// распознавание отбросило кусок), строка уходит сама через HOLD_MS.
//
// При отказе: событий уровня нет (старое ядро, пауза) → голоса нет → прежнее «Ждём речь».
// Хук с подпиской на уровень: lib/use-hearing.ts (здесь только чистая логика для тестов).

/** Сила голоса (voiceAmount), с которой звук считается речью, а не шумом комнаты. */
export const VOICE_ON = 0.2;
/** Сколько держать «Слышу речь» после последнего голоса: пауза VAD 0,5 с + распознавание. */
export const HOLD_MS = 2500;

export interface HearingInput {
  /** Время последнего голоса, мс (performance.now) или null. */
  lastVoiceAt: number | null;
  /** Когда пришла последняя реплика, мс или null. */
  lastTextAt: number | null;
  now: number;
}

/** Есть ли голос, по которому текст ещё не пришёл. */
export function isHearing({ lastVoiceAt, lastTextAt, now }: HearingInput): boolean {
  if (lastVoiceAt === null) return false;
  if (lastTextAt !== null && lastVoiceAt <= lastTextAt) return false;
  return now - lastVoiceAt < HOLD_MS;
}
